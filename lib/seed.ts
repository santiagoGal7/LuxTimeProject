import { slugify } from "@/lib/utils";
import type { Collection, Material, Movement, Order, Product, Variant } from "@/lib/types";

const GALLERY = ["/media/movement.webp", "/media/atelier.webp"];

function variants(stock: number): Variant[] {
  const steel = Math.max(0, Math.ceil(stock * 0.4));
  const leather = Math.max(0, stock - steel);
  const brown = Math.max(0, Math.floor(leather / 2));
  return [
    { id: "cuero", label: "Cuero negro", priceDelta: 0, stock: leather - brown },
    { id: "acero", label: "Brazalete de acero", priceDelta: 350, stock: steel },
    { id: "marron", label: "Piel marrón", priceDelta: 120, stock: brown },
  ];
}

interface Draft {
  name: string;
  brand: string;
  collection: Collection;
  price: number;
  material: Material;
  movement: Movement;
  sizeMm: number;
  stock: number;
  image: string;
  weightG: number;
  waterResistance: string;
  powerReserve: string;
  calibre: string;
  rating: number;
  featured?: boolean;
  description: string;
  story: string;
  complications: string[];
  createdAt: string;
}

function piece(draft: Draft): Product {
  return {
    id: slugify(draft.name),
    slug: slugify(draft.name),
    name: draft.name,
    brand: draft.brand,
    collection: draft.collection,
    price: draft.price,
    material: draft.material,
    movement: draft.movement,
    sizeMm: draft.sizeMm,
    weightG: draft.weightG,
    waterResistance: draft.waterResistance,
    powerReserve: draft.powerReserve,
    calibre: draft.calibre,
    stock: draft.stock,
    rating: draft.rating,
    description: draft.description,
    story: draft.story,
    images: [draft.image, ...GALLERY],
    variants: variants(draft.stock),
    complications: draft.complications,
    featured: Boolean(draft.featured),
    createdAt: draft.createdAt,
  };
}

